<?php

declare(strict_types=1);

namespace Atom\Head;

use Atom\Head\Enum\ColorScheme;

/**
 * Stateless generator populating a `Head` instance from application configuration and page metadata.
 */
final readonly class HeadGenerate
{
    /**
     * @param array<string, mixed> $option
     */
    public static function autoGenerate(Head $head, array $option, object $data): string
    {
        $title = (string) ($data->title ?? '');
        $description = (string) ($data->description ?? '');
        $separator = (string) ($option['separator'] ?? '-');

        if (!empty($option['autoGenerateTitle'])) {
            $title = "{{headTitle}} {$separator} " . $title;
        }
        if (!empty($option['autoGenerateDescription'])) {
            $description = "{{headDescription}} {$separator} " . $description;
        }

        $imageBase = (string) ($data->image ?? '');
        $uri = (string) ($data->uri ?? '');
        $canonical = (string) ($data->canonical ?? '');
        $colorScheme = $option['colorScheme'] instanceof ColorScheme
            ? $option['colorScheme']
            : (ColorScheme::tryFrom((string) ($option['colorScheme'] ?? 'light')) ?? ColorScheme::LIGHT);

        $head->charset()
            ->viewport()
            ->title($title)
            ->description($description)
            ->favicon($imageBase . (string) ($option['iconSvg'] ?? ''))
            ->shortcutIcon($imageBase . (string) ($option['iconIco'] ?? ''))
            ->icon($imageBase . (string) ($option['iconPng'] ?? ''))
            ->robots((string) ($option['robot'] ?? 'index,follow'))
            ->author('Atom Contributors')
            ->authoringTool('Atom')
            ->generator('Atom 2.1')
            ->base($uri)
            ->themeColor((string) ($option['colorTheme'] ?? '#ffffff'), (bool) ($option['isDarkMode'] ?? false))
            ->colorScheme($colorScheme)
            ->canonical($uri . $canonical)
            ->manifest((string) ($data->manifest ?? ''));

        if (!empty($option['autoGenerateOG'])) {
            $head->ogTitle($title)
                ->ogDescription($description)
                ->ogSiteName((string) ($data->title ?? ''))
                ->ogType('website')
                ->ogUrl($uri . $canonical)
                ->ogImage($imageBase . (string) ($option['iconSvg'] ?? ''))
                ->ogImageWidth((string) ($option['iconWith'] ?? $option['iconWidth'] ?? '1200'))
                ->ogImageHeight((string) ($option['iconHeight'] ?? '630'));
        }

        if (!empty($option['autoGenerateApple'])) {
            $iconPng = $imageBase . (string) ($option['iconPng'] ?? '');
            $head->appleMobileWebAppTitle((string) ($data->title ?? ''))
                ->appleMobileWebAppStatusBarStyle('black-translucent')
                ->appleTouchIcon($iconPng)
                ->appleTouchStartupImage($iconPng);
        }

        if (!empty($data->script['scheme']) && \is_string($data->script['scheme'])) {
            $head->scriptText($data->script['scheme'], true);
        }

        return $head->build();
    }

    public static function autoCompleted(): string
    {
        return 'not compleated';
    }
}
